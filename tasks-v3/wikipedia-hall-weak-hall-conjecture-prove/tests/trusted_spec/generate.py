"""Repair-time only: derive a type definition from the original golden input."""
from pathlib import Path
import json

pkg = Path(__file__).resolve().parent
golden = (pkg.parent / 'golden_env/FormalConjecturesBench/Target.lean').read_text()
prefix, rest = golden.split('-- FORMAL_CONJECTURES_BENCH_TARGET_BEGIN', 1)
prefix = prefix.replace('import FormalConjecturesBench.Submission\n', '')
# The final doc-comment documents the removed target, not the extraction command.
prefix = prefix[:prefix.rindex('/--')]
target = rest[:rest.rindex('end Hall')].strip()
source = prefix + '''
-- Elaborate the full target in a temporary environment, then discard its proof
-- and declaration. Only its complete type and ordered universe parameters remain.
open Lean Elab Command in
run_cmd do
  let original ← getEnv
  let stx ← ofExcept <| Parser.runParserCategory (← getEnv) `command ''' + json.dumps(target, ensure_ascii=False) + '''
  elabCommand stx
  let some info := (← getEnv).find? `Hall.weak_hall_conjecture
    | throwError "missing temporary target"
  let expected := info.type
  let levels := info.levelParams
  setEnv original
  liftTermElabM do
    addAndCompile <| .defnDecl {
      name := `FCBTrustedSpec.ExpectedType
      levelParams := levels
      type := ← Meta.inferType expected
      value := expected
      hints := .abbrev
      safety := .safe
    }
end Hall
'''
(pkg / 'FCBTrustedSpec.lean').write_text(source)
